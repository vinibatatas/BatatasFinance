CREATE TABLE Users (
    Id UUID PRIMARY KEY,
    UserName VARCHAR(20) NOT NULL,
    CreatedAt TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE Accounts (
    Id UUID PRIMARY KEY,
    BankName VARCHAR(20) NOT NULL,
    Balance DECIMAL(18,2) NOT NULL,
    UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE
);

CREATE TABLE CreditCards (
    Id UUID PRIMARY KEY,
    Name VARCHAR(20) NOT NULL,
    CreditLimit DECIMAL(18,2) NOT NULL,
    ClosingDay INT NOT NULL,
    DueDay INT NOT NULL,
    UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
    CreditFlag INT NOT NULL,
    CreatedAt TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE Incomes (
    Id UUID PRIMARY KEY,
    Description VARCHAR(60) NOT NULL,
    Amount DECIMAL(18,2) NOT NULL,
    IsRecurring BOOLEAN NOT NULL,
    UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
    CreatedAt TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE Expenses (
    Id UUID PRIMARY KEY,
    Description VARCHAR(60) NOT NULL,
    Amount DECIMAL(18,2) NOT NULL,
    Category INT NOT NULL,
    PaymentMethod INT NOT NULL,
    IsFixed BOOLEAN NOT NULL,
    UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
    CreditCardId UUID NULL REFERENCES CreditCards(Id) ON DELETE SET NULL,
    Installments INT NOT NULL,
    CreatedAt TIMESTAMP WITH TIME ZONE NOT NULL,
    AccountId UUID NOT NULL REFERENCES Accounts(Id) ON DELETE CASCADE
);